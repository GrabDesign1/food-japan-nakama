//
// ⚠️ ここに書いてよいのは、一次情報（下の sources）と当事者から共有された事実だけ。
// 数値・成果・時期を推測で足さない（推測を足すと景表法の優良誤認になりうる）。
// 掲載には関係各社の承諾が要る（2026-08-17 に2件とも承諾済み）。
//
// 事例を追加するときは CASES に1件足すだけでよい（一覧・詳細・サイトマップは自動で増える）。
// 件数が増えて事務局が自分で足したくなったら、そのときにDBモデル化する。

export type CaseSection = {
  /** ■ 見出し（プレスリリース体裁）。省略すると本文だけ続く */
  heading?: string;
  paragraphs: string[];
};

export type CaseStudy = {
  /**
   * 公開するか。**掲載承諾が取れているものだけ true にする**。
   * false にすると一覧・トップ・サイトマップから消え、詳細ページは404になる（定義は残る）。
   */
  published: boolean;
  slug: string;
  /** CASE STUDY 01 の通し番号（素材画像に入っているので合わせる） */
  no: string;
  /** 一覧・詳細の見出し。ニュース記事なので長くてよい */
  title: string;
  /** 見出し下の枠囲み1行 */
  lead: string;
  tags: string[];
  /** 実装の時期（記事の公開日ではない）。一覧の並び替えにも使う */
  period: string;
  /** 並び替え用（新しい順）。YYYYMM */
  sortKey: number;
  /** 時期の補足（「提供開始予定」など）。事実が未確定のときに使う */
  periodNote?: string;
  image: string;
  /** next/image に渡す実寸（WebP変換と表示幅への縮小を効かせるため。素材を差し替えたら必ず直す） */
  imageWidth: number;
  imageHeight: number;
  imageAlt: string;
  /** 一覧カードに出す短い結果 */
  summary: string;
  sections: CaseSection[];
  /** 事実の一覧（商品名・発売日・販売店など） */
  facts: { label: string; value: string }[];
  /** 事実の一覧に付ける注記 */
  factsNote?: string;
  sources: { label: string; url: string }[];
  cta: { heading: string; body: string; label: string; href: string };
};

