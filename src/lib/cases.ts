/**
 * 公開中の事例（表示順）。一覧・トップ・サイトマップは**必ずこれを使う**（`CASES` を直接使わない）。
 * ⚠️ 日付の新しい順ではなく **no（CASE STUDY の通し番号）の昇順**にしている。
 * 画像に「CASE STUDY 01/02」が焼き込まれているため、日付順にすると 02 が 01 の上に出て不自然になる
 * （01=2025年11月／02=2026年7月）。事例を足すときは no を続き番号にすること。
 * sortKey（実装時期）は残してあるので、日付順に戻したくなったらこちらを使う。
 */
export const CASES_SORTED = CASES.filter((c) => c.published).sort((a, b) =>
  a.no.localeCompare(b.no)
);

/** 公開中のものだけ返す（非公開の slug を直接開いても404にするため）。 */
export function findCase(slug: string): CaseStudy | undefined {
  return CASES.find((c) => c.slug === slug && c.published);
}
